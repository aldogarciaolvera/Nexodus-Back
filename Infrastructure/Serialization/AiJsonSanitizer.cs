using System;
using System.Globalization;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;
using Microsoft.Extensions.Logging;
using Nexodus_Back.Core.Exceptions;

namespace Nexodus_Back.Infrastructure.Serialization;

/// <summary>
/// Converter that flexibly parses numeric double values, converting stringified numbers
/// (e.g. "15", "0.5g", "<1") or null into valid double values.
/// </summary>
public partial class FlexibleDoubleConverter : JsonConverter<double>
{
    public override double Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
    {
        if (reader.TokenType == JsonTokenType.Number)
        {
            return reader.GetDouble();
        }

        if (reader.TokenType == JsonTokenType.String)
        {
            var str = reader.GetString();
            if (string.IsNullOrWhiteSpace(str)) return 0.0;

            var match = Regex.Match(str, @"-?\d+(?:\.\d+)?");
            if (match.Success && double.TryParse(match.Value, NumberStyles.Any, CultureInfo.InvariantCulture, out var val))
            {
                return val;
            }

            return 0.0;
        }

        if (reader.TokenType == JsonTokenType.Null)
        {
            return 0.0;
        }

        return 0.0;
    }

    public override void Write(Utf8JsonWriter writer, double value, JsonSerializerOptions options)
    {
        writer.WriteNumberValue(value);
    }
}

/// <summary>
/// Converter that flexibly parses integer values from numbers, strings, or nulls.
/// </summary>
public partial class FlexibleIntConverter : JsonConverter<int>
{
    public override int Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
    {
        if (reader.TokenType == JsonTokenType.Number)
        {
            return reader.GetInt32();
        }

        if (reader.TokenType == JsonTokenType.String)
        {
            var str = reader.GetString();
            if (string.IsNullOrWhiteSpace(str)) return 0;

            var match = Regex.Match(str, @"-?\d+");
            if (match.Success && int.TryParse(match.Value, NumberStyles.Any, CultureInfo.InvariantCulture, out var val))
            {
                return val;
            }

            return 0;
        }

        if (reader.TokenType == JsonTokenType.Null)
        {
            return 0;
        }

        return 0;
    }

    public override void Write(Utf8JsonWriter writer, int value, JsonSerializerOptions options)
    {
        writer.WriteNumberValue(value);
    }
}

/// <summary>
/// Utility to clean, sanitize, and deserialize JSON payloads generated by LLMs (e.g., Google Gemini).
/// Resolves common AI formatting defects such as unquoted units attached to numbers (e.g. 0.0IU, 150kcal, 0g),
/// missing commas, Markdown fences, and conversational preambles/postambles.
/// </summary>
public static partial class AiJsonSanitizer
{
    private static readonly Lazy<JsonSerializerOptions> LazyOptions = new(() =>
    {
        var options = new JsonSerializerOptions
        {
            PropertyNameCaseInsensitive = true,
            AllowTrailingCommas = true,
            ReadCommentHandling = JsonCommentHandling.Skip,
            NumberHandling = JsonNumberHandling.AllowReadingFromString | JsonNumberHandling.AllowNamedFloatingPointLiterals
        };
        options.Converters.Add(new FlexibleDoubleConverter());
        options.Converters.Add(new FlexibleIntConverter());
        return options;
    });

    public static JsonSerializerOptions Options => LazyOptions.Value;

    /// <summary>
    /// Extracts the core JSON payload from an LLM response string.
    /// Strips markdown code blocks (```json ... ```) and conversational text before or after the JSON structure.
    /// </summary>
    public static string ExtractJson(string text)
    {
        if (string.IsNullOrWhiteSpace(text)) return string.Empty;

        var trimmed = text.Trim();

        // 1. If wrapped in markdown code blocks, extract content
        var matchCodeBlock = Regex.Match(trimmed, @"```(?:json)?\s*([\s\S]*?)\s*```", RegexOptions.IgnoreCase);
        if (matchCodeBlock.Success)
        {
            trimmed = matchCodeBlock.Groups[1].Value.Trim();
        }

        // 2. Locate outer '{' or '[' and matching last '}' or ']'
        int firstBrace = trimmed.IndexOf('{');
        int firstBracket = trimmed.IndexOf('[');

        int start = -1;
        int end = -1;

        if (firstBrace >= 0 && firstBracket >= 0)
        {
            if (firstBrace < firstBracket)
            {
                start = firstBrace;
                end = trimmed.LastIndexOf('}');
            }
            else
            {
                start = firstBracket;
                end = trimmed.LastIndexOf(']');
            }
        }
        else if (firstBrace >= 0)
        {
            start = firstBrace;
            end = trimmed.LastIndexOf('}');
        }
        else if (firstBracket >= 0)
        {
            start = firstBracket;
            end = trimmed.LastIndexOf(']');
        }

        if (start >= 0 && end > start)
        {
            return trimmed.Substring(start, end - start + 1);
        }

        return trimmed;
    }

    /// <summary>
    /// Sanitizes common AI malformations in JSON strings, such as unquoted units attached to numbers
    /// (e.g. "carbs": 0.0IU -> "carbs": 0.0), missing commas before next property, etc.
    /// </summary>
    public static string Sanitize(string json)
    {
        if (string.IsNullOrWhiteSpace(json)) return string.Empty;

        // 1. Remove units or text suffixes attached to known numeric properties (e.g. 0.0IU, 10.5g, 250kcal, 0Insignificante)
        const string numericPropsPattern = @"(?i)""(carbs|protein|fat|calories|totalCalories|totalProtein|totalCarbs|totalFat|quantity|prepTimeMinutes|cookTimeMinutes|servings|matchPercentage|stepNumber|confidence|estimatedGrams)""\s*:\s*(-?\d+(?:\.\d+)?)\s*[a-zA-Z]+(?=\s*[,}\]\n\r])";
        json = Regex.Replace(json, numericPropsPattern, "\"$1\": $2");

        // 2. Fix missing comma between number and next property name (e.g. "carbs": 0.0IsOptional: false or "carbs": 0.0 "isOptional": false)
        const string missingCommaPattern = @"(?i)""(carbs|protein|fat|calories|totalCalories|totalProtein|totalCarbs|totalFat|quantity|prepTimeMinutes|cookTimeMinutes|servings|matchPercentage|stepNumber|confidence|estimatedGrams)""\s*:\s*(-?\d+(?:\.\d+)?)\s*""?([a-zA-Z_][a-zA-Z0-9_]*)""?\s*:";
        json = Regex.Replace(json, missingCommaPattern, "\"$1\": $2, \"$3\":");

        // 3. Fallback: clean any other bare numeric values that have invalid trailing letters followed by a delimiter
        json = Regex.Replace(json, @":\s*(-?\d+(?:\.\d+)?)\s*[a-zA-Z]+(?=\s*[,}\]\n\r])", ": $1");

        return json;
    }

    /// <summary>
    /// Deserializes an AI-generated JSON response into the target type <typeparamref name="T"/>,
    /// applying extraction, sanitization, flexible conversions, and controlled exception handling.
    /// </summary>
    public static T Deserialize<T>(string rawAiText, string errorMessage = "No se pudo interpretar la respuesta generada por la IA.", ILogger? logger = null)
    {
        var pureJson = ExtractJson(rawAiText);
        var sanitizedJson = Sanitize(pureJson);

        try
        {
            var result = JsonSerializer.Deserialize<T>(sanitizedJson, Options);
            if (result == null)
            {
                logger?.LogWarning("Deserialized JSON resulted in null for type {Type}. Sanitized payload: {Payload}", typeof(T).Name, sanitizedJson);
                throw new ValidationException(errorMessage);
            }

            return result;
        }
        catch (JsonException ex)
        {
            logger?.LogError(ex, "Error deserializing AI JSON into type {Type}. Raw: {Raw}. Sanitized: {Sanitized}", typeof(T).Name, rawAiText, sanitizedJson);
            throw new ValidationException(errorMessage);
        }
    }
}

